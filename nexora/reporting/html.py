"""Small helpers for self-contained, escaped HTML reports."""
from __future__ import annotations

import html
from typing import Any

import pandas as pd

CSS = """
body{font-family:Segoe UI,Arial,sans-serif;color:#14213d;background:#fbfaf8;margin:0;padding:28px 36px;line-height:1.45}
h1{font-size:23px;margin:0 0 4px}h2{font-size:16px;margin:26px 0 8px;border-bottom:1px solid #dbe2ea;padding-bottom:4px}
.meta{color:#475569;font-size:13px}
table{border-collapse:collapse;width:100%;font-size:13px;margin:6px 0 10px;background:#fff}
th{background:#eef1f5;text-align:left;padding:6px 8px;border:1px solid #dbe2ea}td{padding:5px 8px;border:1px solid #e3e8ef;vertical-align:top}
.ok{color:#0f766e;font-weight:600}.bad{color:#9f1239;font-weight:600}.warn{color:#b45309;font-weight:600}
.note{background:#fff;border-left:3px solid #0f766e;padding:6px 10px;margin:8px 0;font-size:13px}
.wrap{overflow-x:auto}
"""


def esc(v: Any) -> str:
    return html.escape("" if v is None else str(v))


def fmt(v: Any) -> str:
    if v is None or (isinstance(v, float) and v != v):
        return "n/a"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, float):
        return f"{v:,.4g}" if abs(v) < 1e6 else f"{v:,.0f}"
    return str(v)


def table(df: pd.DataFrame | list[dict[str, Any]], max_rows: int = 200) -> str:
    d = pd.DataFrame(df)
    if d.empty:
        return "<p class='meta'>None.</p>"
    head = "".join(f"<th>{esc(c)}</th>" for c in d.columns)
    body = "".join("<tr>" + "".join(f"<td>{esc(fmt(v))}</td>" for v in row) + "</tr>" for row in d.head(max_rows).itertuples(index=False))
    more = f"<p class='meta'>Showing the first {max_rows} of {len(d)} rows.</p>" if len(d) > max_rows else ""
    return f"<div class='wrap'><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>{more}"


def page(title: str, subtitle: str, body: str) -> str:
    return (f"<!doctype html><html lang='en'><head><meta charset='utf-8'><title>{esc(title)}</title><style>{CSS}</style></head><body>"
            f"<h1>{esc(title)}</h1><div class='meta'>{esc(subtitle)}</div>{body}"
            "<p class='meta' style='margin-top:30px'>Generated by Nexora. Every number in this report was computed from the data and settings shown.</p></body></html>")
